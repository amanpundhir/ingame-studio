class TestSchemaValidation:
    """Tests schema validation for all entities defined in data/schema.json."""

    def test_schema_itself_is_valid_draft07(self, schema):
        """Asserts data/schema.json is a valid Draft-07 JSON Schema."""
        Draft7Validator.check_schema(schema)
        assert "$schema" in schema
        assert schema["$schema"] == "http://json-schema.org/draft-07/schema#"
        assert "definitions" in schema

    def test_synthetic_events_conform_to_match_event_schema(self, schema, synthetic_events):
        """Asserts all events in data/synthetic_events.json validate against MatchEvent schema."""
        match_event_subschema = schema["definitions"]["MatchEvent"]
        assert len(synthetic_events) > 0

        # Create validator with resolver for definitions
        validator = Draft7Validator(schema=match_event_subschema)

        for event in synthetic_events:
            validator.validate(event)

    def test_generated_telemetry_frame_conforms_to_schema(self, schema):
        """Asserts frames generated by MatchGenerator validate against TelemetryFrame schema."""
        generator = MatchGenerator(match_id="IGS_2026_TEST", frame_rate=25)
        telemetry_schema = {
            "$schema": "http://json-schema.org/draft-07/schema#",
            "$ref": "#/definitions/TelemetryFrame",
            "definitions": schema["definitions"],
        }
        validator = Draft7Validator(schema=telemetry_schema)

        for _ in range(25):
            frame = generator.step()
            validator.validate(frame)

    def test_fact_pack_conforms_to_schema(self, schema):
        """Asserts a compliant FactPack instance validates cleanly."""
        fact_pack_subschema = schema["definitions"]["FactPack"]
        validator = Draft7Validator(schema=fact_pack_subschema)

        sample_fact_pack = {
            "event_id": "EVT_1009",
            "match_minute": "42:18",
            "passer_name": "Declan Rowe",
            "receiver_name": "Kofi Sarpong",
            "pass_distance_m": 28.5,
            "pass_difficulty": 84.2,
            "ball_speed_kmh": 72.0,
            "chaos_index": 68.0,
            "xt_gained": 0.18,
            "tactical_context": "Broke opposition mid-block across 2 lines of pressure",
        }
        validator.validate(sample_fact_pack)

    def test_verified_insight_conforms_to_schema(self, schema):
        """Asserts a compliant VerifiedInsight instance validates cleanly."""
        insight_subschema = schema["definitions"]["VerifiedInsight"]
        validator = Draft7Validator(schema=insight_subschema)

        sample_insight = {
            "event_id": "EVT_1009",
            "grounding_score": 0.99,
            "casual_story": "Huge break! Declan Rowe threads the needle to Kofi Sarpong!",
            "tactical_analysis": "Rowe breaks City mid-block under 84.2% difficulty.",
            "club_loyalist_story": "Masterclass vision from Declan Rowe!",
            "player_lock_story": "Sarpong receives in space. Peak sprint speed 31.4 km/h.",
            "lower_third_ticker": "TACTICAL BREAKTHROUGH: Declan Rowe (PDR: 84.2%)",
            "verification_status": "VERIFIED",
            "retries_attempted": 0,
        }
        validator.validate(sample_insight)

    def test_broadcast_payload_conforms_to_schema(self, schema):
        """Asserts BroadcastPayload envelopes validate cleanly."""
        broadcast_subschema = schema["definitions"]["BroadcastPayload"]
        validator = Draft7Validator(schema=broadcast_subschema)

        payload = {
            "type": "telemetry",
            "timestamp": "2026-04-18T16:30:00.040000+00:00",
            "data": {"frame_id": 1, "status": "ok"},
        }
        validator.validate(payload)


class TestNegativeSchemaValidation:
    """Asserts schema strictly rejects out-of-bounds or corrupted payloads."""

    def test_reject_player_out_of_bounds_x(self, schema):
        """Asserts player X > 105.0 is rejected."""
        player_subschema = schema["definitions"]["PlayerTracking"]
        bad_player = {
            "player_id": "P_01",
            "team": "home",
            "jersey_number": 9,
            "name": "Invalid Player",
            "role": "FW",
            "x": 106.5,  # Exceeds 105.0
            "y": 34.0,
            "vx": 0.0,
            "vy": 0.0,
            "speed_kmh": 20.0,
        }
        with pytest.raises(ValidationError):
            validate(instance=bad_player, schema=player_subschema)

    def test_reject_player_speed_above_limit(self, schema):
        """Asserts player speed > 40.0 km/h is rejected by schema."""
        player_subschema = schema["definitions"]["PlayerTracking"]
        bad_player = {
            "player_id": "P_01",
            "team": "home",
            "jersey_number": 9,
            "name": "Flash",
            "role": "FW",
            "x": 50.0,
            "y": 34.0,
            "vx": 0.0,
            "vy": 0.0,
            "speed_kmh": 45.0,  # Exceeds max 40.0
        }
        with pytest.raises(ValidationError):
            validate(instance=bad_player, schema=player_subschema)

    def test_reject_invalid_player_count(self, schema):
        """Asserts frames with fewer than 22 players are rejected."""
        telemetry_schema = {
            "$schema": "http://json-schema.org/draft-07/schema#",
            "$ref": "#/definitions/TelemetryFrame",
            "definitions": schema["definitions"],
        }
        validator = Draft7Validator(schema=telemetry_schema)

        generator = MatchGenerator(match_id="IGS_2026_TEST", frame_rate=25)
        frame = generator.step()
        # Drop one player to create 21 players (violates minItems: 22)
        frame["players"] = frame["players"][:21]

        with pytest.raises(ValidationError):
            validator.validate(frame)

    def test_reject_null_player_coordinate(self, schema):
        """Asserts null player coordinate fails schema validation."""
        player_subschema = schema["definitions"]["PlayerTracking"]
        null_coord_player = {
            "player_id": "P_01",
            "team": "home",
            "jersey_number": 9,
            "name": "Null Player",
            "role": "FW",
            "x": None,  # Null coordinate
            "y": 34.0,
            "vx": 0.0,
            "vy": 0.0,
            "speed_kmh": 20.0,
        }
        with pytest.raises(ValidationError):
            validate(instance=null_coord_player, schema=player_subschema)

    def test_reject_unsupported_event_type(self, schema):
        """Asserts unknown event type fails validation."""
        event_subschema = schema["definitions"]["MatchEvent"]
        bad_event = {
            "event_id": "EVT_BAD",
            "match_id": "IGS_2026_TEST",
            "event_type": "handball_invalid",  # Not in enum
            "period": 1,
            "clock": "12:00",
            "frame_index": 500,
            "team": "Northbridge Lions",
            "player_id": "NBL_07",
            "player_name": "Kofi Sarpong",
            "location_x": 50.0,
            "location_y": 30.0,
            "outcome": "complete",
        }
        with pytest.raises(ValidationError):
            validate(instance=bad_event, schema=event_subschema)

    def test_reject_fact_pack_missing_required_fields(self, schema):
        """Asserts FactPack missing required pass_difficulty fails validation."""
        fact_subschema = schema["definitions"]["FactPack"]
        bad_fact_pack = {
            "event_id": "EVT_1009",
            "match_minute": "42:18",
            "passer_name": "Declan Rowe",
            "receiver_name": "Kofi Sarpong",
            "pass_distance_m": 28.5,
            # Missing pass_difficulty
            "ball_speed_kmh": 72.0,
            "chaos_index": 68.0,
            "xt_gained": 0.18,
            "tactical_context": "Broke opposition mid-block",
        }
        with pytest.raises(ValidationError):
            validate(instance=bad_fact_pack, schema=fact_subschema)
